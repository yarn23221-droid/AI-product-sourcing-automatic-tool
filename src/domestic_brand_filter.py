"""
국내/해외 제품 1차 판별 모듈.

네이버 쇼핑의 일반검색(가격비교) 페이지는 봇 접근을 명시적으로 차단하고 있어서 그 페이지를 통한
자동 판별은 하지 않는다 (README 참고). 대신 이미 확보한 상품명 텍스트만으로 "국내 대기업/유명
브랜드가 명시적으로 들어있는가"를 확인하는 키워드 매칭으로 1차 필터링한다.

이 방식의 한계: 브랜드명이 없는 제품, 리스트에 없는 국내 중소 브랜드는 걸러내지 못할 수 있다.
그래서 이 모듈은 "국내 확실" 판정만 신뢰하고, 나머지는 전부 "해외 후보(확인 필요)"로 남겨
사람이 최종 확인하게 한다 - 없는 걸 있다고 지어내지 않는다는 프로젝트 원칙을 그대로 따른다.
"""

# 디지털/가전 베스트 랭킹에 자주 등장하는 국내 대기업/유명 브랜드 (계속 보완 필요한 휴리스틱 목록)
DOMESTIC_BRAND_KEYWORDS = [
    "삼성", "갤럭시", "LG", "엘지", "쿠쿠", "쿠첸", "위닉스", "코웨이", "청호나이스",
    "위니아", "대유위니아", "한샘", "락앤락", "리큅", "휴롬", "브리츠", "슈피겐",
    "미닉스", "이지언", "쿠첸", "신일전자", "신일", "한경희", "삼성전자", "LG전자",
    "카카오", "네이버", "당근", "토스", "현대", "기아", "쏘카", "ipTIME", "아이피타임",
]


def is_domestic_brand(title: str) -> bool:
    """상품명에 국내 유명 브랜드 키워드가 포함되어 있으면 True(국내 제품으로 확실)를 반환한다.

    False라고 해서 반드시 해외 제품이라는 뜻은 아니다 - "국내 브랜드라고 확신할 근거가 없다"는 뜻일
    뿐이니, 최종 판단은 사람이 한 번 더 확인해야 한다.
    """
    return any(keyword in title for keyword in DOMESTIC_BRAND_KEYWORDS)


if __name__ == "__main__":
    tests = [
        "[PS5]플레이스테이션프로 디스크",
        "삼성전자 갤럭시 버즈4 프로 R640",
        "8bitdo FlipPad 플립패드 접이식 게임패드",
        "LG전자 그램 노트북",
    ]
    for t in tests:
        print(f"{'국내(확실)' if is_domestic_brand(t) else '해외 후보(확인 필요)'} - {t}")
